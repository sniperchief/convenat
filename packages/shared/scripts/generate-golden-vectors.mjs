/**
 * Regenerate vectors/golden.json from the built package and the shipped fixtures.
 *
 *   npm run vectors:generate --workspace @covenant/shared
 *
 * The expected values in the vector file are produced by the implementation,
 * once, and then committed. The test suite asserts against the committed file,
 * never against a freshly computed value - so any future change to the schema,
 * the normalisation rules or the encoder breaks the tests loudly instead of
 * silently redefining the protocol.
 *
 * Consequently: DO NOT run this script to make a failing test pass. A diff in
 * this file is a breaking protocol change and requires a specification version
 * bump, not a regeneration.
 */

import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import {
  CONDITION_SPEC_VERSION,
  CURRENT_EVIDENCE_PACKAGE_VERSION,
  EVIDENCE_PACKAGE_VERSION_1,
  SUPPORTED_EVIDENCE_PACKAGE_VERSIONS,
  UNORDERED_FIELDS,
  buildEvidenceCommitment,
  buildRulesCommitment,
} from '../dist/index.js';
import { conditionSpecFixtures, evidencePackageFixtures } from '../dist/testing/fixtures.js';

const here = dirname(fileURLToPath(import.meta.url));
const outputDirectory = resolve(here, '..', 'vectors');
const outputPath = resolve(outputDirectory, 'golden.json');

mkdirSync(outputDirectory, { recursive: true });

const conditionSpecs = Object.entries(conditionSpecFixtures).map(([name, input]) => {
  const { canonical, rulesHash } = buildRulesCommitment(input);
  return { name, input, canonical, rulesHash };
});

const evidencePackages = Object.entries(evidencePackageFixtures).map(([name, input]) => {
  const { canonical, evidenceHash } = buildEvidenceCommitment(input);
  return { name, input, canonical, evidenceHash };
});

const document = {
  $comment:
    'Golden vectors for the Covenant canonicalisation and hashing protocol. Generated by packages/shared/scripts/generate-golden-vectors.mjs. A change to any expected value here is a breaking protocol change.',
  producer: '@covenant/shared',
  conditionSpecVersion: CONDITION_SPEC_VERSION,
  /**
   * Frozen at the first evidence version, which is what this field meant when
   * M1 wrote it. `evidencePackageVersions` is the field to read.
   */
  evidencePackageVersion: EVIDENCE_PACKAGE_VERSION_1,
  evidencePackageVersions: [...SUPPORTED_EVIDENCE_PACKAGE_VERSIONS],
  currentEvidencePackageVersion: CURRENT_EVIDENCE_PACKAGE_VERSION,
  algorithm: {
    canonicalization: 'RFC 8785 (JCS), restricted profile: integers only, no optional keys',
    encoding: 'UTF-8',
    digest: 'keccak256 (Ethereum, as used by Solidity keccak256)',
    pipeline: 'validate -> normalise unordered sets -> JCS -> UTF-8 -> keccak256',
    unorderedFields: {
      conditionSpec: [...UNORDERED_FIELDS.conditionSpec],
      /** EvidencePackage v1.0 — frozen; nothing is unordered. */
      evidencePackage: [...UNORDERED_FIELDS.evidencePackage],
      /** EvidencePackage v2.0. */
      evidencePackageV2: [...UNORDERED_FIELDS.evidencePackageV2],
    },
  },
  conditionSpecs,
  evidencePackages,
};

writeFileSync(outputPath, `${JSON.stringify(document, null, 2)}\n`, 'utf8');

console.log(`Wrote ${outputPath}`);
console.log(`  ${conditionSpecs.length} condition spec vector(s)`);
for (const vector of conditionSpecs) {
  console.log(`    ${vector.name.padEnd(16)} ${vector.rulesHash}`);
}
console.log(`  ${evidencePackages.length} evidence package vector(s)`);
for (const vector of evidencePackages) {
  console.log(
    `    ${vector.name.padEnd(22)} v${String(vector.input.version).padEnd(4)} ${vector.evidenceHash}`,
  );
}
